  /// Translate a key for given language code ('hi', 'mr', 'en')
  static String tr(String key, String langCode) {
    final entry = _strings[key];
    if (entry == null) return key;

    final target = entry[langCode];
    if (target != null && target.isNotEmpty) {
      return target;
    }

    // Fallback to Hindi, then English, then raw key
    return entry['hi'] ?? entry['en'] ?? key;
  }

  /// Convenience inline translation helper
  static String t(String lang, {required String en, required String mr, required String hi}) {
    if (lang == 'mr') return mr;
    if (lang == 'en') return en;
    return hi;
  }
